"""Generate supabase/seed.sql (DEMO data only) from supabase/merchants_seed.csv.

The merchants come from the Notion "Targeted Merchants" database. They are sales
prospects, NOT signed partners -- never load this seed into production.
Branches, QR codes and perks are derived inside Postgres, deterministically from the
merchant name, so every environment gets the same QR codes (handy for testing).
"""
import csv, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(root / "supabase/merchants_seed.csv", encoding="utf-8")))
q = lambda s: "'" + s.replace("'", "''") + "'"
CAT = {"Eat & Drink": "Coffee", "Restaurants": "Food"}

values = ",\n".join(
    f"  ({q(r['name'])}, {q(CAT.get(r['category'], r['category']))}, {q(r['subcategory'])}, "
    f"{int(r['ideal_discount'].split('-')[0].rstrip('%'))}, {int(r['ideal_discount'].split('-')[-1].rstrip('%'))}, {q(r['priority'])})"
    for r in rows
)

sql = f"""-- DEMO SEED (generated by scripts/gen_seed.py). Do not use in production.
-- 10 campuses (approximate coordinates), 89 merchants from the Notion prospect list,
-- 1-2 branches each near a campus, one cashier QR per branch, 1-2 perks per merchant.

insert into public.campuses (name, short_name, city, lat, lng) values
  ('American University in Cairo', 'AUC', 'New Cairo', 30.0195, 31.4999),
  ('German University in Cairo', 'GUC', 'New Cairo', 29.9866, 31.4413),
  ('The British University in Egypt', 'BUE', 'El Shorouk', 30.1186, 31.6058),
  ('Cairo University', 'CU', 'Giza', 30.0276, 31.2101),
  ('Ain Shams University', 'ASU', 'Cairo', 30.0770, 31.2852),
  ('Misr International University', 'MIU', 'Cairo', 30.1676, 31.4917),
  ('MSA University', 'MSA', '6th of October', 29.9697, 30.9502),
  ('Nile University', 'NU', 'Sheikh Zayed', 30.0716, 30.9729),
  ('Alexandria University', 'AlexU', 'Alexandria', 31.2058, 29.9187),
  ('Arab Academy for Science & Technology', 'AAST', 'Alexandria', 31.3093, 30.0640);

create temporary table seed_merchants (name text, category text, subcategory text, low int, high int, priority text);
insert into seed_merchants values
{values};

insert into public.merchants (name, category, subcategory, brand_type, description, status)
select name, category, subcategory,
       case when priority = 'High' then 'chain' else 'local' end,
       subcategory || ' — student perks at ' || name || '.', 'live'
  from seed_merchants;

-- Branches: High-priority merchants get 2, others 1; campus picked from a hash of the name; ~100 m jitter.
with c as (select row_number() over (order by name) - 1 as i, * from public.campuses),
b as (
  select m.id as merchant_id, m.name, j,
         ('x' || substr(md5(m.name), 1, 8))::bit(32)::int as h,
         ('x' || substr(md5(m.name || j), 1, 8))::bit(32)::int as jitter
    from public.merchants m join seed_merchants s on s.name = m.name
    cross join lateral generate_series(0, case when s.priority = 'High' then 1 else 0 end) j
)
insert into public.merchant_branches (merchant_id, name, address, city, campus_id, lat, lng)
select b.merchant_id, b.name || ' – ' || c.short_name, 'Near ' || c.name, c.city, c.id,
       c.lat + ((abs(b.jitter) % 200) - 100) / 100000.0,
       c.lng + ((abs(b.jitter / 256) % 200) - 100) / 100000.0
  from b join c on c.i = (abs(b.h) + b.j * 3) % 10;  -- second branch goes to a different campus

-- One cashier QR per branch, deterministic code (PK- + 10 hex chars)
insert into public.branch_qr_codes (branch_id, code, label)
select id, 'PK-' || upper(substr(md5(name), 1, 10)), 'Cashier' from public.merchant_branches;

-- Perks: base discount for everyone; boosted perk (min spend 200) when the ideal range is wider
insert into public.perks (merchant_id, title, description, discount_type, discount_value, min_spend, priority_score)
select m.id, s.low || '% off for students', 'Show your Perkly success screen to the cashier.', 'percentage', s.low, 0,
       case when s.priority = 'High' then 10 else 0 end
  from public.merchants m join seed_merchants s on s.name = m.name;

insert into public.perks (merchant_id, title, description, discount_type, discount_value, max_discount_amount, min_spend, is_flash, end_at, priority_score)
select m.id, s.high || '% off — min spend 200 EGP', 'Boosted perk for bigger orders.', 'percentage', s.high, 150, 200,
       (row_number() over (order by s.name)) % 4 = 1,
       case when (row_number() over (order by s.name)) % 4 = 1 then now() + interval '3 days' end,
       5
  from public.merchants m join seed_merchants s on s.name = m.name
 where s.high > s.low;

drop table seed_merchants;
"""
(root / "supabase/seed.sql").write_text(sql, encoding="utf-8")
print(f"merchants={len(rows)} bytes={len(sql)}")
