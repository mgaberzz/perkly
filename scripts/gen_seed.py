"""Generate supabase/seed.sql (DEMO data only) from supabase/merchants_seed.csv.

The merchants come from the Notion "Targeted Merchants" database. They are sales
prospects, NOT signed partners -- never load this seed into production.
Coordinates are approximate campus locations, for local development only.
"""
import csv, hashlib, pathlib, uuid

root = pathlib.Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(root / "supabase/merchants_seed.csv", encoding="utf-8")))

NS = uuid.UUID("6f1d7c2e-8a7b-4c7e-9a51-2f0e0b5c1a11")
def uid(*parts): return str(uuid.uuid5(NS, "|".join(parts)))
def q(s): return "'" + str(s).replace("'", "''") + "'" if s is not None else "null"

campuses = [  # name, short, city, lat, lng (approximate)
    ("American University in Cairo", "AUC", "New Cairo", 30.0195, 31.4999),
    ("German University in Cairo", "GUC", "New Cairo", 29.9866, 31.4413),
    ("The British University in Egypt", "BUE", "El Shorouk", 30.1186, 31.6058),
    ("Cairo University", "CU", "Giza", 30.0276, 31.2101),
    ("Ain Shams University", "ASU", "Cairo", 30.0770, 31.2852),
    ("Misr International University", "MIU", "Cairo", 30.1676, 31.4917),
    ("MSA University", "MSA", "6th of October", 29.9697, 30.9502),
    ("Nile University", "NU", "Sheikh Zayed", 30.0716, 30.9729),
    ("Alexandria University", "AlexU", "Alexandria", 31.2058, 29.9187),
    ("Arab Academy for Science & Technology", "AAST", "Alexandria", 31.3093, 30.0640),
]

# Map Notion categories to app categories
CAT = {"Eat & Drink": "Coffee", "Restaurants": "Food"}
EMOJI_DESC = {"Food": "🍔", "Coffee": "☕", "Fashion": "👟", "Beauty": "💄", "Fitness": "💪",
              "Entertainment": "🎮", "Electronics": "📱", "Transport": "🛴", "Services": "🛠️"}

out = ["-- DEMO SEED (generated by scripts/gen_seed.py). Do not use in production.", ""]
out.append("insert into public.campuses (id, name, short_name, city, lat, lng) values")
out.append(",\n".join(f"  ({q(uid('campus', c[1]))}, {q(c[0])}, {q(c[1])}, {q(c[2])}, {c[3]}, {c[4]})" for c in campuses) + ";")
out.append("")

m_rows, b_rows, qr_rows, p_rows = [], [], [], []
for i, r in enumerate(rows):
    name = r["name"]
    cat = CAT.get(r["category"], r["category"])
    mid, h = uid("merchant", name), int(hashlib.md5(name.encode()).hexdigest(), 16)
    brand = "chain" if r["priority"] == "High" else "local"
    desc = f"{EMOJI_DESC.get(cat, '✨')} {r['subcategory']} — student perks at {name}."
    m_rows.append(f"  ({q(mid)}, {q(name)}, {q(cat)}, {q(r['subcategory'])}, {q(brand)}, {q(desc)}, 'live')")

    # one or two branches near campuses
    n_branches = 2 if r["priority"] == "High" else 1
    for j in range(n_branches):
        c = campuses[(h + j * 3) % len(campuses)]
        bid = uid("branch", name, str(j))
        dlat = ((h >> (8 + j)) % 200 - 100) / 100000.0  # within ~100 m
        dlng = ((h >> (16 + j)) % 200 - 100) / 100000.0
        b_rows.append(f"  ({q(bid)}, {q(mid)}, {q(name + ' – ' + c[1])}, {q('Near ' + c[0])}, {q(c[2])}, {q(uid('campus', c[1]))}, {c[3] + dlat:.6f}, {c[4] + dlng:.6f})")
        code = "PK-" + hashlib.sha1(f"{name}{j}".encode()).hexdigest()[:10].upper()
        qr_rows.append(f"  ({q(bid)}, {q(code)}, 'Cashier')")

    low = int(r["ideal_discount"].split("-")[0].rstrip("%"))
    high = int(r["ideal_discount"].split("-")[-1].rstrip("%"))
    p_rows.append(f"  ({q(uid('perk', name, 'main'))}, {q(mid)}, {q(f'{low}% off for students')}, {q('Show your Perkly success screen to the cashier.')}, 'percentage', {low}, null, 0, false, {10 if r['priority']=='High' else 0})")
    if high > low:
        p_rows.append(f"  ({q(uid('perk', name, 'boost'))}, {q(mid)}, {q(f'{high}% off — min spend 200 EGP')}, {q('Boosted perk for bigger orders.')}, 'percentage', {high}, 150, 200, {'true' if i % 4 == 0 else 'false'}, 5)")

out.append("insert into public.merchants (id, name, category, subcategory, brand_type, description, status) values")
out.append(",\n".join(m_rows) + ";\n")
out.append("insert into public.merchant_branches (id, merchant_id, name, address, city, campus_id, lat, lng) values")
out.append(",\n".join(b_rows) + ";\n")
out.append("insert into public.branch_qr_codes (branch_id, code, label) values")
out.append(",\n".join(qr_rows) + ";\n")
out.append("insert into public.perks (id, merchant_id, title, description, discount_type, discount_value, max_discount_amount, min_spend, is_flash, priority_score) values")
out.append(",\n".join(p_rows) + ";\n")
out.append("-- flash perks end 3 days from seeding\nupdate public.perks set end_at = now() + interval '3 days' where is_flash;\n")

(root / "supabase/seed.sql").write_text("\n".join(out), encoding="utf-8")
print(f"campuses={len(campuses)} merchants={len(m_rows)} branches={len(b_rows)} perks={len(p_rows)}")
